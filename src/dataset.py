# src/dataset.py
"""
PyTorch Dataset and DataLoader utilities for CASIA v2 ELA maps.

Expects the following directory layout (generated by src/ela.py):

    data/ela/
    ├── Au/    # Authentic ELA maps (.png)
    └── Tp/    # Tampered  ELA maps (.png)

Labels:
    0 = authentic  (Au)
    1 = tampered   (Tp)
"""

import logging
from pathlib import Path
from typing import Optional

import numpy as np
import torch
from PIL import Image
from sklearn.model_selection import train_test_split
from torch.utils.data import DataLoader, Dataset

from src.utils import load_config

logger = logging.getLogger(__name__)

# ── Label mapping ────────────────────────────────────────────────────────────
FOLDER_TO_LABEL = {"Au": 0, "Tp": 1}
LABEL_NAMES = {0: "authentic", 1: "tampered"}


# ── Dataset ──────────────────────────────────────────────────────────────────

class ForgeryDataset(Dataset):
    """PyTorch Dataset for ELA-processed forgery detection images.

    Each sample is an ELA map loaded as a float32 tensor normalised to [0, 1]
    and resized to (input_size × input_size).  ImageNet normalisation is
    applied so that pretrained backbones receive expected input statistics.

    Args:
        image_paths: List of absolute image file paths.
        labels: Corresponding integer labels (0 or 1).
        input_size: Spatial resolution to resize images to.
        mean: Per-channel mean for normalisation.
        std: Per-channel std for normalisation.
    """

    def __init__(
        self,
        image_paths: list,
        labels: list,
        input_size: int = 224,
        mean: tuple = (0.485, 0.456, 0.406),
        std: tuple = (0.229, 0.224, 0.225),
    ) -> None:
        assert len(image_paths) == len(labels)
        self.image_paths = image_paths
        self.labels = labels
        self.input_size = input_size
        self.mean = np.array(mean, dtype=np.float32).reshape(1, 1, 3)
        self.std = np.array(std, dtype=np.float32).reshape(1, 1, 3)

    def __len__(self) -> int:
        return len(self.image_paths)

    def __getitem__(self, idx: int):
        path = self.image_paths[idx]
        label = self.labels[idx]

        # Load and resize
        img = Image.open(path).convert("RGB")
        img = img.resize((self.input_size, self.input_size), Image.BILINEAR)

        # Convert to float32 [0, 1] → normalise → CHW tensor
        arr = np.array(img, dtype=np.float32) / 255.0
        arr = (arr - self.mean) / self.std
        tensor = torch.from_numpy(arr).permute(2, 0, 1)  # HWC → CHW

        return tensor, label


class RobustnessDataset(Dataset):
    """Dataset that applies corruptions to raw images and computes ELA on-the-fly.
    
    Used strictly for robustness evaluation to ensure physical correctness
    (corruptions are applied to images, not to already-computed residual maps).
    """

    def __init__(
        self,
        image_paths: list,
        labels: list,
        transform=None,
        input_size: int = 224,
        ela_quality: int = 90,
        ela_scale: int = 15,
        mean: tuple = (0.485, 0.456, 0.406),
        std: tuple = (0.229, 0.224, 0.225),
    ) -> None:
        assert len(image_paths) == len(labels)
        self.image_paths = image_paths
        self.labels = labels
        self.transform = transform
        self.input_size = input_size
        self.ela_quality = ela_quality
        self.ela_scale = ela_scale
        self.mean = np.array(mean, dtype=np.float32).reshape(1, 1, 3)
        self.std = np.array(std, dtype=np.float32).reshape(1, 1, 3)

    def __len__(self) -> int:
        return len(self.image_paths)

    def __getitem__(self, idx: int):
        from src.ela import compute_ela
        import cv2

        path = self.image_paths[idx]
        label = self.labels[idx]

        # 1. Load raw image
        # cv2 loads as BGR, we convert to RGB for Albumentations/PIL
        img_bgr = cv2.imread(path)
        if img_bgr is None:
            raise FileNotFoundError(f"Failed to read image: {path}")
        img_rgb = cv2.cvtColor(img_bgr, cv2.COLOR_BGR2RGB)

        # 2. Apply corruption (if any)
        if self.transform is not None:
            augmented = self.transform(image=img_rgb)
            img_rgb = augmented["image"]

        # 3. Compute ELA on the fly (requires PIL image or numpy array)
        ela_map = compute_ela(img_rgb, quality=self.ela_quality, scale=self.ela_scale)
        
        # 4. Resize and normalize
        ela_pil = Image.fromarray(ela_map).resize((self.input_size, self.input_size), Image.BILINEAR)
        arr = np.array(ela_pil, dtype=np.float32) / 255.0
        arr = (arr - self.mean) / self.std
        tensor = torch.from_numpy(arr).permute(2, 0, 1)

        return tensor, label


# ── Data collection & splitting ──────────────────────────────────────────────

def collect_ela_paths(ela_dir: str, extensions: set) -> tuple:
    """Walk the ELA directory and return (paths, labels) lists.

    Args:
        ela_dir: Root directory of ELA maps (e.g. ``data/ela``).
        extensions: Set of allowed file extensions (e.g. ``{".png"}``).

    Returns:
        Tuple of (image_paths, labels) where each is a list.
    """
    ela_path = Path(ela_dir)
    paths, labels = [], []

    for folder_name, label in FOLDER_TO_LABEL.items():
        folder = ela_path / folder_name
        if not folder.exists():
            logger.warning("Missing class folder: %s", folder)
            continue
        for fp in sorted(folder.iterdir()):
            if fp.is_file() and fp.suffix.lower() in extensions:
                paths.append(str(fp))
                labels.append(label)

    logger.info(
        "Collected %d images from %s  (authentic=%d, tampered=%d)",
        len(paths), ela_dir,
        labels.count(0), labels.count(1),
    )
    return paths, labels


def create_data_loaders(
    config: Optional[dict] = None,
    *,
    config_path: str = "configs/config.yaml",
) -> dict:
    """Build train / val / test DataLoaders from the ELA directory.

    Uses stratified splitting to preserve class ratios.  All parameters
    are read from the config SSOT.

    Args:
        config: Pre-loaded config dict (falls back to *config_path*).
        config_path: Path to YAML config.

    Returns:
        Dict with keys ``"train"``, ``"val"``, ``"test"`` mapping to
        DataLoader instances, plus ``"num_train"``, ``"num_val"``,
        ``"num_test"`` counts.
    """
    if config is None:
        config = load_config(config_path)

    ela_dir = config["dataset"]["ela_dir"]
    extensions = {ext.lower() for ext in config["dataset"]["image_extensions"]}
    # ELA maps are always saved as .png
    extensions.add(".png")

    train_split = config["dataset"]["train_split"]
    val_split = config["dataset"]["val_split"]
    seed = config["dataset"]["random_seed"]
    input_size = config["model"]["input_size"]
    batch_size = config["training"]["batch_size"]
    num_workers = config["training"]["num_workers"]
    pin_memory = config["training"]["pin_memory"]

    norm_cfg = config["augmentation"]["val"]["normalize"]
    mean = tuple(norm_cfg["mean"])
    std = tuple(norm_cfg["std"])

    # ── Collect & split ──────────────────────────────────────────────────
    paths, labels = collect_ela_paths(ela_dir, extensions)
    if len(paths) == 0:
        raise RuntimeError(
            f"No ELA images found in '{ela_dir}'. "
            "Run the ELA pipeline first:  python -m src.ela"
        )

    # Optional subset
    subset_size = config["dataset"].get("subset_size")
    if subset_size is not None and subset_size < len(paths):
        from sklearn.model_selection import train_test_split as _split
        paths, _, labels, _ = _split(
            paths, labels, train_size=subset_size,
            stratify=labels, random_state=seed,
        )
        logger.info("Using documented subset: %d images", len(paths))

    # First split: train vs (val + test)
    val_test_ratio = val_split + (1.0 - train_split - val_split)
    X_train, X_rest, y_train, y_rest = train_test_split(
        paths, labels,
        test_size=val_test_ratio,
        stratify=labels,
        random_state=seed,
    )

    # Second split: val vs test (equal halves of the remainder)
    test_ratio_of_rest = (1.0 - train_split - val_split) / val_test_ratio
    X_val, X_test, y_val, y_test = train_test_split(
        X_rest, y_rest,
        test_size=test_ratio_of_rest,
        stratify=y_rest,
        random_state=seed,
    )

    logger.info("Split sizes — train=%d, val=%d, test=%d", len(X_train), len(X_val), len(X_test))

    # ── Build datasets & loaders ─────────────────────────────────────────
    ds_train = ForgeryDataset(X_train, y_train, input_size, mean, std)
    ds_val = ForgeryDataset(X_val, y_val, input_size, mean, std)
    ds_test = ForgeryDataset(X_test, y_test, input_size, mean, std)

    loaders = {
        "train": DataLoader(
            ds_train, batch_size=batch_size, shuffle=True,
            num_workers=num_workers, pin_memory=pin_memory,
        ),
        "val": DataLoader(
            ds_val, batch_size=batch_size, shuffle=False,
            num_workers=num_workers, pin_memory=pin_memory,
        ),
        "test": DataLoader(
            ds_test, batch_size=batch_size, shuffle=False,
            num_workers=num_workers, pin_memory=pin_memory,
        ),
        "num_train": len(X_train),
        "num_val": len(X_val),
        "num_test": len(X_test),
    }
    return loaders


def get_test_split_raw_paths(
    config: Optional[dict] = None,
    *,
    config_path: str = "configs/config.yaml",
) -> tuple:
    """Retrieve the exact raw image paths corresponding to the test split.
    
    This guarantees that the robustness evaluation runs on the exact same
    samples as the clean evaluation by reversing the ELA map paths back to
    their raw source files.
    """
    if config is None:
        config = load_config(config_path)
        
    # Generate the identical splits (deterministic seeding)
    loaders = create_data_loaders(config)
    test_ds = loaders["test"].dataset
    ela_paths = test_ds.image_paths
    labels = test_ds.labels
    
    raw_dir = Path(config["dataset"]["root_dir"])
    image_extensions = config["dataset"]["image_extensions"]
    
    raw_paths = []
    for ela_p in ela_paths:
        ela_path = Path(ela_p)
        class_name = ela_path.parent.name
        stem = ela_path.stem
        
        found = False
        for ext in image_extensions:
            possible_path = raw_dir / class_name / f"{stem}{ext}"
            if possible_path.exists():
                raw_paths.append(str(possible_path))
                found = True
                break
                
        if not found:
            raise FileNotFoundError(
                f"Could not trace ELA map back to raw image. "
                f"Missing stem '{stem}' in {raw_dir / class_name}"
            )
            
    return raw_paths, labels
